// key is a signing key pair: RSA or EC, never both.
type key struct {
	kid string
	rsa *rsa.PrivateKey
	ec  *ecdsa.PrivateKey
}

func (k *key) alg() string {
	if k.rsa != nil {
		return "RS256"
	}
	return "ES256"
}

// keyring is every key the fixtures use.
type keyring struct {
	rsaCurrent  *key // published; signs the valid RS256 tokens
	ecCurrent   *key // published; signs the valid ES256 tokens
	rsaAttacker *key // never published
	rsaWeak     *key // published, but only 1024 bits: must not be loaded
	ecP384      *key // published, but the wrong curve for ES256: must not be loaded
	rsaEnc      *key // published with use=enc: must not be loaded
	rsaPS256    *key // published with alg=PS256: must not be loaded
}

func (r *keyring) all() []*key {
	return []*key{r.rsaCurrent, r.ecCurrent, r.rsaAttacker, r.rsaWeak, r.ecP384, r.rsaEnc, r.rsaPS256}
}

func generateKeys() *keyring {
	newRSA := func(kid string, bits int) *key {
		k, err := rsa.GenerateKey(rand.Reader, bits)
		must(err)
		return &key{kid: kid, rsa: k}
	}
	newEC := func(kid string, curve elliptic.Curve) *key {
		k, err := ecdsa.GenerateKey(curve, rand.Reader)
		must(err)
		return &key{kid: kid, ec: k}
	}
	return &keyring{
		rsaCurrent:  newRSA("rsa-current", 2048),
		ecCurrent:   newEC("ec-current", elliptic.P256()),
		rsaAttacker: newRSA("rsa-attacker", 2048),
		rsaWeak:     newRSA("rsa-weak-1024", 1024),
		ecP384:      newEC("ec-p384", elliptic.P384()),
		rsaEnc:      newRSA("rsa-enc", 2048),
		rsaPS256:    newRSA("rsa-ps256", 2048),
	}
}

func b64(b []byte) string { return base64.RawURLEncoding.EncodeToString(b) }

func unb64(s string) *big.Int {
	b, err := base64.RawURLEncoding.DecodeString(s)
	must(err)
	return new(big.Int).SetBytes(b)
}

func (k *key) publicJWK() map[string]any {
	if k.rsa != nil {
		return map[string]any{
			"kty": "RSA", "kid": k.kid,
			"n": b64(k.rsa.N.Bytes()),
			"e": b64(big.NewInt(int64(k.rsa.E)).Bytes()),
		}
	}
	// Bytes is the uncompressed SEC 1 point: 0x04 || X || Y.
	point, err := k.ec.PublicKey.Bytes()
	must(err)
	size := (len(point) - 1) / 2
	return map[string]any{
		"kty": "EC", "kid": k.kid, "crv": k.ec.Curve.Params().Name,
		"x": b64(point[1 : 1+size]),
		"y": b64(point[1+size:]),
	}
}

func (k *key) privateJWK() map[string]string {
	out := map[string]string{}
	for name, v := range k.publicJWK() {
		out[name] = v.(string)
	}
	if k.rsa != nil {
		out["d"] = b64(k.rsa.D.Bytes())
		out["p"] = b64(k.rsa.Primes[0].Bytes())
		out["q"] = b64(k.rsa.Primes[1].Bytes())
		out["dp"] = b64(k.rsa.Precomputed.Dp.Bytes())
		out["dq"] = b64(k.rsa.Precomputed.Dq.Bytes())
		out["qi"] = b64(k.rsa.Precomputed.Qinv.Bytes())
		return out
	}
	d, err := k.ec.Bytes()
	must(err)
	out["d"] = b64(d)
	return out
}

func (r *keyring) privateJWKs() []map[string]string {
	var out []map[string]string
	for _, k := range r.all() {
		out = append(out, k.privateJWK())
	}
	return out
}

// jwks is what the issuer publishes. Besides the two keys that sign valid
// tokens it contains keys an implementation must refuse to load, so that the
// fixtures also pin down key-set filtering.
func (r *keyring) jwks() map[string]any {
	with := func(k *key, extra map[string]any) map[string]any {
		j := k.publicJWK()
		for name, v := range extra {
			j[name] = v
		}
		return j
	}
	return map[string]any{"keys": []any{
		with(r.rsaCurrent, map[string]any{"use": "sig", "alg": "RS256"}),
		with(r.ecCurrent, map[string]any{"use": "sig", "alg": "ES256"}),
		with(r.rsaWeak, map[string]any{"use": "sig", "alg": "RS256"}),
		with(r.ecP384, map[string]any{"use": "sig"}),
		with(r.rsaEnc, map[string]any{"use": "enc"}),
		with(r.rsaPS256, map[string]any{"use": "sig", "alg": "PS256"}),
	}}
}

func loadKeys(fixtures []byte) (*keyring, error) {
	var fx Fixtures
	if err := json.Unmarshal(fixtures, &fx); err != nil {
		return nil, err
	}
	byKid := map[string]*key{}
	for _, j := range fx.Keys {
		k := &key{kid: j["kid"]}
		switch j["kty"] {
		case "RSA":
			k.rsa = &rsa.PrivateKey{
				PublicKey: rsa.PublicKey{N: unb64(j["n"]), E: int(unb64(j["e"]).Int64())},
				D:         unb64(j["d"]),
				Primes:    []*big.Int{unb64(j["p"]), unb64(j["q"])},
			}
			k.rsa.Precompute()
			if err := k.rsa.Validate(); err != nil {
				return nil, fmt.Errorf("key %q: %w", k.kid, err)
			}
		case "EC":
			curve := elliptic.P256()
			if j["crv"] == "P-384" {
				curve = elliptic.P384()
			}
			// The public point is recomputed from the private scalar.
			ec, err := ecdsa.ParseRawPrivateKey(curve, decode(j["d"]))
			if err != nil {
				return nil, fmt.Errorf("key %q: %w", k.kid, err)
			}
			k.ec = ec
		default:
			return nil, fmt.Errorf("key %q: unknown kty %q", k.kid, j["kty"])
		}
		byKid[k.kid] = k
	}
	r := &keyring{
		rsaCurrent: byKid["rsa-current"], ecCurrent: byKid["ec-current"], rsaAttacker: byKid["rsa-attacker"],
		rsaWeak: byKid["rsa-weak-1024"], ecP384: byKid["ec-p384"], rsaEnc: byKid["rsa-enc"], rsaPS256: byKid["rsa-ps256"],
	}
	for _, k := range r.all() {
		if k == nil {
			return nil, errors.New("a key is missing; regenerate with -new-keys")
		}
	}
	return r, nil
}


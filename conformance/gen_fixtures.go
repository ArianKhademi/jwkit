// Command conformance generates fixtures.json, the shared test vectors that
// the Go and TypeScript implementations of jwkit must agree on, and doubles as
// a tiny test issuer (see serve.go).
//
//	go run .            regenerate fixtures.json
//	go run . -check     fail if fixtures.json is not what the generator produces
//	go run . -new-keys  regenerate with fresh key pairs
//	go run . -serve :8089   serve the fixture JWKS and mint tokens
//	go run . -mutations 5000 -seed 1   write random mutations (see mutate.go)
//
// It uses only the Go standard library: tokens are built by hand and signed
// with crypto/rsa and crypto/ecdsa, so neither JOSE library under test had a
// hand in producing its own test vectors.
//
// Output is deterministic. Keys are reused from the existing fixtures.json,
// RSASSA-PKCS1-v1_5 is deterministic by definition, and ECDSA signatures use
// RFC 6979 nonces, so regenerating changes nothing unless a case changed.
// That is what makes the -check mode, which CI runs, possible.
package main


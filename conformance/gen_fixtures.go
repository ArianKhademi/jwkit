// sign returns the JWS signature of signingInput in the key's own algorithm.
func (k *key) sign(signingInput string) []byte {
	digest := sha256.Sum256([]byte(signingInput))
	if k.rsa != nil {
		sig, err := rsa.SignPKCS1v15(nil, k.rsa, crypto.SHA256, digest[:])
		must(err)
		return sig
	}
	r, s := k.ecdsaRS(digest[:])
	size := (k.ec.Curve.Params().BitSize + 7) / 8
	sig := make([]byte, 2*size)
	r.FillBytes(sig[:size])
	s.FillBytes(sig[size:])
	return sig
}

// signDER returns the ECDSA signature in ASN.1 DER, the encoding JWS does not use.
func (k *key) signDER(signingInput string) []byte {
	digest := sha256.Sum256([]byte(signingInput))
	// A nil random source selects deterministic RFC 6979 nonces.
	der, err := k.ec.Sign(nil, digest[:], crypto.SHA256)
	must(err)
	return der
}

func (k *key) ecdsaRS(digest []byte) (r, s *big.Int) {
	der, err := k.ec.Sign(nil, digest, crypto.SHA256)
	must(err)
	var sig struct{ R, S *big.Int }
	_, err = asn1.Unmarshal(der, &sig)
	must(err)
	return sig.R, sig.S
}

type obj = map[string]any

// toJSON encodes with sorted keys, which keeps the output deterministic.
func toJSON(v any) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	must(enc.Encode(v))
	return strings.TrimSuffix(buf.String(), "\n")
}

// signed assembles and signs a token from literal header and payload text.
func (k *key) signed(header, payload string) string {
	input := b64([]byte(header)) + "." + b64([]byte(payload))
	return input + "." + b64(k.sign(input))
}

func (k *key) header(extra ...obj) obj {
	h := obj{"alg": k.alg(), "kid": k.kid, "typ": "JWT"}
	for _, e := range extra {
		for name, v := range e {
			if v == nil {
				delete(h, name)
			} else {
				h[name] = v
			}
		}
	}
	return h
}

// claims returns a payload that is valid at `now`, with overrides applied.
// A nil override removes the claim.
func claims(overrides ...obj) obj {
	c := obj{"iss": issuer, "aud": audience, "sub": "user-123", "iat": now - 10, "exp": now + 3600}
	for _, o := range overrides {
		for name, v := range o {
			if v == nil {
				delete(c, name)
			} else {
				c[name] = v
			}
		}
	}
	return c
}

// token signs claims (with overrides) under the key's default header.
func (k *key) token(overrides ...obj) string {
	return k.signed(toJSON(k.header()), toJSON(claims(overrides...)))
}

// tokenWithHeader signs default claims under a modified header.
func (k *key) tokenWithHeader(extra obj) string {
	return k.signed(toJSON(k.header(extra)), toJSON(claims()))
}

// as returns the same key pair under a different kid.
func (k *key) as(kid string) *key {
	c := *k
	c.kid = kid
	return &c
}

func split(token string) (h, p, s string) {
	parts := strings.Split(token, ".")
	if len(parts) != 3 {
		panic("split: not a three-segment token")
	}
	return parts[0], parts[1], parts[2]
}

func decode(segment string) []byte {
	b, err := base64.RawURLEncoding.DecodeString(segment)
	must(err)
	return b
}

// paddedTo returns a validly signed token of exactly n bytes, by sizing a
// filler claim. Lengths that the base64 arithmetic cannot reach with one
// header are reached with another.
func (k *key) paddedTo(n int) string {
	sigLen := len(b64(k.sign("x")))
	for _, extra := range []obj{{}, {"typ": nil}, {"typ": "at+jwt"}, {"typ": "JOSE"}} {
		header := toJSON(k.header(extra))
		for pad := 0; pad <= n; pad++ {
			payload := toJSON(claims(obj{"pad": strings.Repeat("x", pad)}))
			size := base64.RawURLEncoding.EncodedLen(len(header)) + 1 + base64.RawURLEncoding.EncodedLen(len(payload)) + 1 + sigLen
			if size == n {
				return k.signed(header, payload)
			}
			if size > n {
				break
			}
		}
	}
	panic(fmt.Sprintf("cannot build a token of exactly %d bytes", n))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

